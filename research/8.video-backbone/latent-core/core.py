"""L1: a fixed pretrained MobileIE + learned latent recurrence baseline.

Standard recurrent gates, not a novelty or calibrated uncertainty claim. Unlike
the old transport/moment states, the candidate state is generated by a CNN.
"""
import copy

import torch
from torch import nn
import torch.nn.functional as F


class Separable(nn.Sequential):
    def __init__(self, inputs, outputs, dilation):
        super().__init__(nn.Conv2d(inputs, inputs, 3, padding=dilation,
                                   dilation=dilation, groups=inputs),
                         nn.Conv2d(inputs, outputs, 1))


class LatentCore(nn.Module):
    def __init__(self, original):
        super().__init__()
        self.backbone = copy.deepcopy(original).requires_grad_(True)
        self.norm = nn.LayerNorm(12, eps=1e-5)
        self.project = nn.Conv2d(12, 32, 1)
        self.gates = Separable(64, 64, 4)
        self.candidate = Separable(64, 32, 8)
        self.readout = nn.Conv2d(32, 12, 1)
        nn.init.zeros_(self.readout.weight)
        nn.init.zeros_(self.readout.bias)
        assert sum(p.numel() for p in self.parameters()) == 12431

    def forward(self, image, state=None, history="causal"):
        if image.ndim != 4 or image.shape[1] != 3 or min(image.shape[-2:]) < 4:
            raise ValueError("Expected BCHW RGB with minimum side 4")
        if history not in ("causal", "current"):
            raise ValueError("Expected causal or current history route")
        net = self.backbone
        z = net.head.block1(image)
        pooled = F.avg_pool2d(z, 4, 4, ceil_mode=True)
        normalized = self.norm(pooled.permute(0, 2, 3, 1)).permute(0, 3, 1, 2)
        embedded = self.project(normalized).tanh()
        if state is not None and (state.shape != embedded.shape or state.device != embedded.device
                                  or state.dtype != embedded.dtype):
            raise ValueError("State shape/device/dtype changed; reset the sequence")
        previous = embedded if state is None or history == "current" else state
        reset, update = self.gates(torch.cat([embedded, previous], 1)).sigmoid().chunk(2, 1)
        candidate = self.candidate(torch.cat([embedded, reset * previous], 1)).tanh()
        next_state = (1 - update) * previous + update * candidate
        correction = F.interpolate(self.readout(next_state), size=z.shape[-2:],
                                   mode="bilinear", align_corners=False)
        z = z + correction
        head = (net.head.weight1 * z) * (net.head.weight2 * z) + net.head.bias
        body = net.body(head)
        channel = net.att(body)
        spatial = net.att1((channel * body).max(1, keepdim=True).values)
        return net.tail((spatial * channel) * body), next_state


def models(original, seed):
    with torch.random.fork_rng(devices=[]):
        torch.manual_seed(9100 + seed)
        first = LatentCore(original)
    return {"spatial": first, "causal": copy.deepcopy(first)}


def sequence(model, clip, history="causal"):
    state, outputs = None, []
    for frame in clip.unbind(1):
        value, state = model(frame, state, history)
        outputs.append(value)
    return torch.stack(outputs, 1), state


class Streaming:
    def __init__(self, model, history="causal"):
        self.model = model
        self.history = history
        self.state = None

    def reset(self):
        self.state = None

    def step(self, image):
        value, state = self.model(image, self.state, self.history)
        self.state = state.detach().clone(memory_format=torch.contiguous_format)
        return value

    def state_bytes(self):
        return 0 if self.state is None else self.state.untyped_storage().nbytes()


def optimizer(model):
    original = list(model.backbone.parameters())
    original_ids = {id(p) for p in original}
    added = [p for p in model.parameters() if id(p) not in original_ids]
    return torch.optim.Adam([dict(params=original, lr=1e-5), dict(params=added, lr=1e-3)],
                            betas=(.9, .999), eps=1e-8, weight_decay=0)
